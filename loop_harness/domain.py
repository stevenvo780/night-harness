"""Domain objects shared by the harness pipeline."""
from __future__ import annotations

import time
from dataclasses import dataclass, field
from pathlib import Path

import memory


def safe_subpath(base, rel: str):
    """Resuelve `rel` dentro de `base` y verifica contención (anti path-traversal).

    Devuelve el `Path` resuelto si queda DENTRO de `base`; `None` si `rel` es
    vacío, absoluto, o escapa del worktree vía `..`. La salida de un modelo
    (hunter/fixer) no debe poder leer/escribir fuera del worktree aislado.
    """
    if not rel:
        return None
    base_resolved = Path(base).resolve()
    candidate = (base_resolved / rel).resolve()
    if candidate == base_resolved:
        return None
    if base_resolved not in candidate.parents:
        return None
    return candidate


@dataclass
class Suspect:
    """Bug hypothesis generated by hunter or E2E workers."""

    file: str
    line: int
    snippet: str
    why: str
    severity: str = 'medium'
    repro: str = ''
    confidence: float = 0.0
    samples: int = 0
    first_seen: float = field(default_factory=time.time)
    refuted: bool = False
    hash: str = ''
    source: str = 'hunter'

    def __post_init__(self) -> None:
        self.hash = memory.hash_suspect(self.file, self.line, self.snippet)


@dataclass
class Bug:
    """Bug confirmed or being evaluated by judges."""

    suspect: Suspect
    votes_real: int = 0
    votes_not_bug: int = 0
    voters: list[str] = field(default_factory=list)

